const {
  generateBatch,
  generateTxtString,
  generateCsvString,
} = require("../lib/luhn");
const { fetchBinInfo } = require("../lib/handyBin");

const recentStore = new Map();

async function tgApi(token, method, body) {
  const res = await fetch(`https://api.telegram.org/bot${token}/${method}`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  if (!res.ok) {
    const errText = await res.text();
    console.error(`Telegram ${method} failed:`, res.status, errText);
  }
  return res;
}

async function sendMessage(token, chatId, text, extra = {}) {
  return tgApi(token, "sendMessage", {
    chat_id: chatId,
    text,
    parse_mode: "Markdown",
    ...extra,
  });
}

async function sendDocumentBuffer(token, chatId, filename, contentString) {
  const form = new FormData();
  form.append("chat_id", String(chatId));
  const blob = new Blob([contentString], { type: "text/plain;charset=utf-8" });
  form.append("document", blob, filename);

  const res = await fetch(`https://api.telegram.org/bot${token}/sendDocument`, {
    method: "POST",
    body: form,
  });
  if (!res.ok) {
    const errText = await res.text();
    console.error("Telegram sendDocument failed:", res.status, errText);
  }
}

function extractCardsFromMessageText(messageText) {
  if (!messageText) return null;
  const matches = messageText.match(/\b\d{13,19}\|\d{2}\|\d{4}\|\d{3,4}\b/g);
  return matches && matches.length > 0 ? matches : null;
}

function parseGenInput(text) {
  const binMatch = text.match(/(?:\.gen|\/gen)?\s*(\d{6,15})/);
  if (!binMatch) return null;

  const countMatch = text.match(/x(\d{1,3})/i);
  const expMatch = text.match(/\b(\d{1,2})[|/](\d{2,4})\b/);

  let expMonth = null;
  let expYear = null;
  if (expMatch) {
    expMonth = expMatch[1].padStart(2, "0");
    const rawYear = expMatch[2];
    expYear = rawYear.length === 2 ? `20${rawYear}` : rawYear;
  }

  return {
    binCode: binMatch[1],
    count: countMatch ? Number(countMatch[1]) : 1,
    expMonth,
    expYear,
  };
}

function parseBinInput(text) {
  const binMatch = text.match(/(?:\.bin|\/bin)?\s*(\d{6,15})/);
  return binMatch ? binMatch[1] : null;
}

async function handleGenCommand(token, chatId, rawText) {
  const parsed = parseGenInput(rawText);
  if (!parsed) {
    await sendMessage(
      token,
      chatId,
      "⚠️ Usage: `/gen <bin> x<qty> MM|YYYY`\nExample: `/gen 434769 09|28 x10`"
    );
    return;
  }

  const results = generateBatch(parsed);
  recentStore.set(chatId, results);

  const binInfo = await fetchBinInfo(parsed.binCode);
  const countryStr = `${binInfo.country} ${binInfo.emoji}`.trim();
  const cardList = results.join("\n");

  const keyboard = {
    inline_keyboard: [
      [
        { text: "⬇️ Export .txt", callback_data: "export_txt" },
        { text: "⬇️ Export .csv", callback_data: "export_csv" },
      ],
    ],
  };

  const replyText =
    `💳 *Issuer:* ${binInfo.scheme}\n` +
    `🏦 *Bank:* ${binInfo.bank}\n` +
    `🌍 *Country:* ${countryStr}\n` +
    `📦 *Type:* ${binInfo.type}\n` +
    `💎 *Level:* ${binInfo.brand}\n` +
    `🔢 *Generated ${results.length} Cards:*\n` +
    `\`\`\`\n${cardList}\n\`\`\`\n` +
    `Generated by @Blast_of_Boom`;

  await sendMessage(token, chatId, replyText, { reply_markup: keyboard });
}

async function handleBinCommand(token, chatId, rawText) {
  const binCode = parseBinInput(rawText);
  if (!binCode) {
    await sendMessage(token, chatId, "⚠️ Usage: `/bin <6-15 digit BIN>`");
    return;
  }

  const binInfo = await fetchBinInfo(binCode);
  const countryStr = `${binInfo.country} ${binInfo.emoji}`.trim();

  const replyText =
    `🔍 *BIN Lookup:* \`${binCode}\`\n` +
    `💳 *Scheme:* ${binInfo.scheme}\n` +
    `🏦 *Bank:* ${binInfo.bank}\n` +
    `🌍 *Country:* ${countryStr}\n` +
    `💼 *Type:* ${binInfo.type}\n` +
    `💎 *Level:* ${binInfo.brand}\n` +
    `\nGenerated by @Blast_of_Boom`;

  await sendMessage(token, chatId, replyText);
}

async function handleCallbackQuery(token, callbackQuery) {
  const cbId = callbackQuery.id;
  const msg = callbackQuery.message;
  const chatId = msg?.chat?.id;
  const dataType = callbackQuery.data;

  await tgApi(token, "answerCallbackQuery", { callback_query_id: cbId });

  if (!chatId) return;

  const fromText = extractCardsFromMessageText(msg?.text);
  const cards = fromText || recentStore.get(chatId);

  if (!cards || cards.length === 0) {
    if (msg?.message_id) {
      await tgApi(token, "editMessageText", {
        chat_id: chatId,
        message_id: msg.message_id,
        text: "❌ No recent generation found.",
      });
    }
    return;
  }

  if (dataType === "export_txt") {
    await sendDocumentBuffer(
      token,
      chatId,
      "cards.txt",
      generateTxtString(cards)
    );
  } else if (dataType === "export_csv") {
    await sendDocumentBuffer(
      token,
      chatId,
      "cards.csv",
      generateCsvString(cards)
    );
  }
}

module.exports = async function handler(req, res) {
  if (req.method === "GET") {
    return res.status(200).json({ ok: true, service: "card-gen-vercel-bot" });
  }

  if (req.method !== "POST") {
    return res.status(405).json({ error: "Method Not Allowed" });
  }

  const token = process.env.BOT_TOKEN;
  if (!token) {
    return res.status(500).json({ error: "BOT_TOKEN is missing" });
  }

  const expectedSecret = process.env.WEBHOOK_SECRET;
  if (expectedSecret) {
    const receivedSecret = req.headers["x-telegram-bot-api-secret-token"];
    if (receivedSecret !== expectedSecret) {
      return res.status(401).json({ error: "Unauthorized" });
    }
  }

  const update = req.body || {};

  try {
    if (update.callback_query) {
      await handleCallbackQuery(token, update.callback_query);
      return res.status(200).json({ ok: true });
    }

    const message = update.message || update.edited_message;
    if (!message || !message.chat?.id || typeof message.text !== "string") {
      return res.status(200).json({ ok: true });
    }

    const chatId = message.chat.id;
    const text = message.text.trim();
    const lower = text.toLowerCase();

    if (lower === "/start" || lower.startsWith("/start ")) {
      await sendMessage(
        token,
        chatId,
        "👋 Welcome to card gen bot by @Blast_of_Boom — the card generator!\n\n" +
          "Use `/gen <bin> x<qty> MM|YYYY` to generate cards.\n\n" +
          "*Examples:*\n" +
          "Value: `/gen 457821`\n" +
          "Bulk: `/gen 457821 x10`\n" +
          "Custom Date: `/gen 457821 09|28 x10`\n" +
          "Full Date: `/gen 457821 09|2028`\n\n" +
          "Or simply type:\n" +
          "`.gen 457821 09|28`"
      );
      return res.status(200).json({ ok: true });
    }

    if (lower === "/help" || lower.startsWith("/help ")) {
      await sendMessage(
        token,
        chatId,
        "📘 *How to use @revgenbot:*\n\n" +
          "`/gen <bin>` - Generate 1 card\n" +
          "`/gen <bin> x10` - Generate 10 cards\n" +
          "`/gen <bin> 08|28` - Generate with date 08/2028\n" +
          "`/gen <bin> x5 08|2030` - Mix quantity and date\n\n" +
          "**Formats supported:** `MM|YY`, `MM|YYYY`\n" +
          "**Amex Support:** Start BIN with 34 or 37 for 15-digit generation.\n\n" +
          "`/bin <bin>` or `.bin <bin>` - Lookup BIN details."
      );
      return res.status(200).json({ ok: true });
    }

    if (lower.startsWith("/gen") || lower.startsWith(".gen")) {
      await handleGenCommand(token, chatId, text);
      return res.status(200).json({ ok: true });
    }

    if (lower.startsWith("/bin") || lower.startsWith(".bin")) {
      await handleBinCommand(token, chatId, text);
      return res.status(200).json({ ok: true });
    }

    return res.status(200).json({ ok: true });
  } catch (err) {
    console.error("Webhook handler error:", err);
    return res.status(200).json({ ok: true });
  }
};
